#ifndef _uprops_h_
# define _uprops_h_

/* Unicode character properties (uprops).

   The tables are generated by gen-uprops from the UCD files in
   src/unicode/ucd/ (see README there) and cover the code points
   0 .. 0x10FFFF.  Every function takes a Unicode code point.  A value above
   0x10FFFF gets the neutral answer: category Cn, East Asian Width N, script
   Unknown, width 1, font group FALLBACK, not a word character, not graphic,
   and no case mapping.

   Until the editor's Char holds a Unicode code point, a caller has to
   convert the internal value to a code point first.  The tables are not
   used by anything else yet. */

/* General category (UnicodeData.txt field 2).  The order is the order of
   uc_category_name (). */
enum uc_category_t
{
  UC_Lu, UC_Ll, UC_Lt, UC_Lm, UC_Lo,
  UC_Mn, UC_Mc, UC_Me,
  UC_Nd, UC_Nl, UC_No,
  UC_Pc, UC_Pd, UC_Ps, UC_Pe, UC_Pi, UC_Pf, UC_Po,
  UC_Sm, UC_Sc, UC_Sk, UC_So,
  UC_Zs, UC_Zl, UC_Zp,
  UC_Cc, UC_Cf, UC_Cs, UC_Co, UC_Cn,
  UC_CATEGORY_MAX
};

/* East Asian Width (EastAsianWidth.txt). */
enum uc_east_asian_width_t
{
  UC_EA_N, UC_EA_A, UC_EA_F, UC_EA_H, UC_EA_Na, UC_EA_W
};

/* Font group: which font slot draws the character (design 6.2).  The slots
   are chosen from the script and the block.  UC_FONT_HAN is the slot of the
   buffer's Han language (jp, kr, gb or big5); UC_FONT_JP is always the
   Japanese slot (kana, CJK punctuation, full width forms). */
enum uc_font_group_t
{
  UC_FONT_ASCII,
  UC_FONT_JP,
  UC_FONT_HAN,
  UC_FONT_HANGUL,
  UC_FONT_GREEK,
  UC_FONT_CYRILLIC,
  UC_FONT_GEORGIAN,
  UC_FONT_LATIN,                /* Latin, IPA, modifiers, diacriticals */
  UC_FONT_FALLBACK,
  UC_FONT_MAX
};

int uc_category (u_int32_t);
const char *uc_category_name (int);          /* "Lu", "Ll", ... */
int uc_east_asian_width (u_int32_t);
const char *uc_east_asian_width_name (int);  /* "N", "A", "F", "H", "Na", "W" */
int uc_script (u_int32_t);
const char *uc_script_name (int);            /* "Latin", "Hiragana", ... */

/* The display width in cells: 0 for non-spacing and enclosing marks, format
   characters and controls (the display layer decides how to show a control
   character), 2 for East Asian Wide and Fullwidth, 1 otherwise.  A character
   of East Asian Width Ambiguous gets AMBIGUOUS, which is 1 or 2 (anything
   other than 1 is taken as 2).  The one-argument form uses
   *east-asian-ambiguous-width* (default 2). */
int uc_width (u_int32_t, int ambiguous);
int uc_width (u_int32_t);
int uc_ambiguous_width ();

/* The font group.  When AMBIGUOUS is 2, a character of East Asian Width
   Ambiguous (Greek, Cyrillic, box drawing, the circle and so on) is drawn
   with the Han language slot, as it is when the file is cp932. */
int uc_font_group (u_int32_t, int ambiguous);
int uc_font_group (u_int32_t);

/* A word constituent: a letter, a mark or a number (L*, M*, N*). */
int uc_word_char_p (u_int32_t);
/* Not a control, format, surrogate, unassigned, line or paragraph separator
   (not Cc, Cf, Cs, Cn, Zl, Zp). */
int uc_graphic_p (u_int32_t);

/* Simple case mappings (UnicodeData.txt) and simple case folding
   (CaseFolding.txt, status C and S).  They return the code point itself when
   there is no mapping. */
u_int32_t uc_toupper (u_int32_t);
u_int32_t uc_tolower (u_int32_t);
u_int32_t uc_totitle (u_int32_t);
u_int32_t uc_casefold (u_int32_t);

const char *uc_unicode_version ();
int uc_table_bytes ();                       /* the size of all the tables */

#endif /* _uprops_h_ */
