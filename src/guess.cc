# include "ed.h"
# include "byte-stream.h"
# include "guess.h"

/* data types */
typedef struct guess_arc_rec
{
    unsigned int next;          /* next state */
    double score;               /* score */
} guess_arc;

typedef struct guess_dfa_rec
{
    signed char (*states)[256];
    guess_arc *arcs;
    int state;
    double score;
} guess_dfa;

/* macros */
#define DFA_INIT(st, ar) \
    { st, ar, 0, 1.0 }

#define DFA_NEXT(dfa, ch)                               \
    do {                                                \
        int arc__;                                      \
        if (dfa.state >= 0) {                           \
            arc__ = dfa.states[dfa.state][ch];          \
            if (arc__ < 0) {                            \
                dfa.state = -1;                         \
            } else {                                    \
                dfa.state = dfa.arcs[arc__].next;       \
                dfa.score *= dfa.arcs[arc__].score;     \
            }                                           \
        }                                               \
    } while (0)

#define DFA_ALIVE(dfa)  ((dfa).state >= 0)

/* include DFA table generated by guess.scm */
#include "guess_tab.c"

static lisp
get_utf8_encoding (char *sig, size_t siglen)
{
  return (utf8_signature_p (sig, siglen)
          ? Vencoding_default_utf8
          : Vencoding_default_utf8n);
}

static lisp
make_pair (lisp encoding, double score)
{
  return xcons (symbol_value_char_encoding (encoding),
                make_double_float (score));
}

lisp
Fguess_char_encoding (lisp string)
{
  return guess_char_encoding (string, 1);
}

/* Every candidate is dead.  DIED[] is the position of the byte that killed
   each candidate (eucj, sjis, utf8, big5; the length of the data if it ended
   in the middle of a character).  The candidate that read the most is the
   one the data is nearly written in: a file that is nearly utf-8 with a
   stray byte is utf-8.  When two or more died at the same place (a stray
   byte at the start, or in ASCII) nothing is known and the caller uses its
   default encoding (sjis), which keeps the bytes. */
static lisp
guess_longest_survivor (const int *died, const char *sig, size_t siglen)
{
  int best = -1, n = 0;
  for (int i = 0; i < 4; i++)
    if (best < 0 || died[i] > died[best])
      {
        best = i;
        n = 1;
      }
    else if (died[i] == died[best])
      n++;
  if (n != 1)
    return Qnil;
  switch (best)
    {
    case 0:
      return list (make_pair (Vencoding_euc_jp, 1.0));
    case 1:
      return list (make_pair (Vencoding_sjis, 1.0));
    case 2:
      return list (make_pair (get_utf8_encoding ((char *)sig, siglen), 1.0));
    default:
      return list (make_pair (Vencoding_big5, 1.0));
    }
}

/* COMPLETE is true when STRING is the whole of the data.  A candidate
   that ends in the middle of a character is then a broken sequence
   and is not a candidate.  When STRING is only the head of the data,
   the cut may be anywhere and is not judged. */
lisp
guess_char_encoding (lisp string, int complete)
{
  guess_dfa eucj = DFA_INIT(guess_eucj_st, guess_eucj_ar);
  guess_dfa sjis = DFA_INIT(guess_sjis_st, guess_sjis_ar);
  guess_dfa utf8 = DFA_INIT(guess_utf8_st, guess_utf8_ar);
  guess_dfa big5 = DFA_INIT(guess_big5_st, guess_big5_ar);

  xstream_ibyte_helper is (string);
  if (is-> eofp ())
    return Qnil;

  char sig[3];
  size_t siglen = 0;
  int died[4] = {-1, -1, -1, -1};
  int nbytes = 0;
  for (int c = is->get (), i = 0; c != xstream::eof; c = is->get (), i++)
    {
      nbytes = i + 1;
      if (siglen < sizeof sig)
        sig[siglen++] = c;

      /* special treatment of iso-2022 escape sequence */
      if (c == 0x1b && !is->eofp ())
        {
          c = (unsigned char) is->peek ();
          if (c == '$' || c == '(')
            return list (make_pair (Vencoding_jis, 1.0));
        }

      /* special treatment of BOM */
      if (i == 0 && c == 0xff && !is->eofp ())
        {
          c = (unsigned char) is->peek ();
          if (c == 0xfe)
            return list (make_pair (Vencoding_default_utf16le_bom, 1.0));
        }
      if (i == 0 && c == 0xfe && !is->eofp ())
        {
          c = (unsigned char) is->peek ();
          if (c == 0xff)
            return list (make_pair (Vencoding_default_utf16be_bom, 1.0));
        }

      /* Every candidate reads every byte.  A candidate that is the only
         one alive is not chosen before it has read the rest: the byte
         that killed the others may kill it too (BUG-0039). */
      DFA_NEXT(eucj, c);
      DFA_NEXT(sjis, c);
      DFA_NEXT(utf8, c);
      DFA_NEXT(big5, c);

      if (!DFA_ALIVE(eucj) && died[0] < 0) died[0] = i;
      if (!DFA_ALIVE(sjis) && died[1] < 0) died[1] = i;
      if (!DFA_ALIVE(utf8) && died[2] < 0) died[2] = i;
      if (!DFA_ALIVE(big5) && died[3] < 0) died[3] = i;

      if (!DFA_ALIVE(eucj) && !DFA_ALIVE(sjis) && !DFA_ALIVE(utf8) && !DFA_ALIVE(big5))
        {
          /* we ran out the possibilities */
          return guess_longest_survivor (died, sig, siglen);
        }
    }

  if (complete)
    {
      /* The data ends in the middle of a character: broken. */
      guess_dfa *all[] = { &eucj, &sjis, &utf8, &big5 };
      for (int i = 0; i < numberof (all); i++)
        if (all[i]->state > 0)
          {
            all[i]->state = -1;
            died[i] = nbytes;
          }
      if (!DFA_ALIVE(eucj) && !DFA_ALIVE(sjis) && !DFA_ALIVE(utf8) && !DFA_ALIVE(big5))
        return guess_longest_survivor (died, sig, siglen);
    }

  /* Now, we have ambigous code. */
  guess_dfa *order[] = { &utf8, &sjis, &eucj, &big5 };
  lisp result = Qnil;
  for (int i = numberof (order) - 1; i >= 0; i--)
    {
      lisp encoding = Qnil;
      if (!DFA_ALIVE (*order[i])) continue;
      if (order[i] == &eucj)
        encoding = Vencoding_euc_jp;
      else if (order[i] == &utf8)
        encoding = get_utf8_encoding (sig, siglen);
      else if (order[i] == &sjis)
        encoding = Vencoding_sjis;
      else if (order[i] == &big5)
        encoding = Vencoding_big5;
      else
        assert (0);

      result = xcons (make_pair (encoding, order[i]->score), result);
    }

  return result;
}
